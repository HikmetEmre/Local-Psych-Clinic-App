<#
  Nil Psikoloji - Klinik: native Windows setup. Run by the installer (elevated).

  Office computer (mode=office), fresh install:
    - creates the database (PostgreSQL 16, 127.0.0.1:55432) as Windows service KlinikPostgres
    - generates every secret, writes them to ProgramData\...\config\klinik.env (Admins/SYSTEM only)
    - creates this computer's HTTPS certificate and trusts it here; firewall rule for the
      PRIVATE office network only (the owner's laptop syncs over it)
    - runs migrations, creates the admin user
    - installs services KlinikApp (https://localhost:8443) and KlinikJobs
    - connects Google Drive (backups + daily snapshot) if asked
    - writes the KEY SHEET to the desktop: print it, store it offline, delete the file
  Owner's laptop (mode=laptop), fresh install:
    - checks BitLocker (warns if the disk is not encrypted)
    - reads the pairing file (keys, office address, certificate, token)
    - creates its own database, migrates, copies everything from the office (first sync)
    - installs service KlinikApp only (https://localhost:8443, this computer only)
  Upgrade (database already exists): keeps data, keys and the kind of installation.
#>
param([Parameter(Mandatory = $true)][string]$Params)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version 2

# ---------------------------------------------------------------- parameters
$p = @{}
foreach ($line in Get-Content -LiteralPath $Params -Encoding UTF8) {
    $i = $line.IndexOf('=')
    if ($i -gt 0) { $p[$line.Substring(0, $i)] = $line.Substring($i + 1) }
}
Remove-Item -LiteralPath $Params -Force -ErrorAction SilentlyContinue

$App = $p['app']
$Data = $p['data']
$Py = Join-Path $App 'python\python.exe'
$PgBin = Join-Path $App 'pgsql\bin'
$Config = Join-Path $Data 'config'
$Tls = Join-Path $Config 'tls'
$EnvFile = Join-Path $Config 'klinik.env'
$PgData = Join-Path $Data 'pgdata'
$Logs = Join-Path $Data 'logs'
$Port = 55432
$HttpsPort = 8443
$LocalUrl = "https://localhost:$HttpsPort"
$Host_ = $env:COMPUTERNAME

foreach ($d in @($Data, $Config, $Tls, $Logs, (Join-Path $Data 'backups'), (Join-Path $Data 'ozet'))) {
    New-Item -ItemType Directory -Force -Path $d | Out-Null
}
$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
Start-Transcript -Path (Join-Path $Logs "setup-$stamp.log") | Out-Null

function Step($text) { Write-Host ''; Write-Host "==> $text" -ForegroundColor Green }
function New-Secret {
    $bytes = New-Object byte[] 24
    [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    -join ($bytes | ForEach-Object { $_.ToString('x2') })
}
function Invoke-Checked([string]$exe, [string[]]$arguments) {
    & $exe @arguments
    if ($LASTEXITCODE -ne 0) { throw "$([IO.Path]::GetFileName($exe)) exited with $LASTEXITCODE" }
}
function Read-EnvFile {
    $values = [ordered]@{}
    foreach ($line in Get-Content -LiteralPath $EnvFile -Encoding UTF8) {
        $i = $line.IndexOf('=')
        if ($i -gt 0 -and -not $line.StartsWith('#')) { $values[$line.Substring(0, $i)] = $line.Substring($i + 1) }
    }
    $values
}
function Write-EnvFile($values) {
    $lines = @('# Nil Psikoloji - Klinik. Generated by setup. Readable only by SYSTEM and Administrators.')
    foreach ($k in $values.Keys) { $lines += "$k=$($values[$k])" }
    [IO.File]::WriteAllLines($EnvFile, $lines, (New-Object Text.UTF8Encoding($false)))
}
function Invoke-Manage([string[]]$arguments) {
    $out = & $Py -m klinik_local.service --env $EnvFile manage @arguments 2>&1
    if ($LASTEXITCODE -ne 0) { throw "manage $($arguments[0]) failed: $out" }
    $out
}

$fresh = -not (Test-Path (Join-Path $PgData 'PG_VERSION'))
$sheet = @()

try {
    # Only Administrators and SYSTEM may read the configuration (it holds the keys).
    & icacls $Config /inheritance:r /grant:r 'SYSTEM:(OI)(CI)F' '*S-1-5-32-544:(OI)(CI)F' | Out-Null

    # Services of this and of earlier versions (KlinikKasa / KlinikSync were the cloud era).
    foreach ($id in @('KlinikApp', 'KlinikJobs', 'KlinikKasa', 'KlinikSync')) {
        if (Get-Service -Name $id -ErrorAction SilentlyContinue) {
            Step "Stopping $id"
            Stop-Service -Name $id -Force -ErrorAction SilentlyContinue
        }
    }
    foreach ($old in @('KlinikKasa', 'KlinikSync')) {
        $exe = Join-Path $App "services\$old.exe"
        if ((Get-Service -Name $old -ErrorAction SilentlyContinue) -and (Test-Path $exe)) {
            & $exe uninstall | Out-Null
        }
    }

    if ($fresh) {
        $mode = $p['mode']
        if ($mode -ne 'laptop') { $mode = 'office' }
    } else {
        $existing = Read-EnvFile
        $mode = if ($existing['LOCAL_MODE'] -eq 'replica') { 'laptop' } else { 'office' }
    }
    Step "Installation: $(if ($mode -eq 'laptop') { "owner's laptop (copy)" } else { 'office computer' })"

    if ($mode -eq 'laptop') {
        Step 'Checking disk encryption (BitLocker)'
        $protected = $false
        try {
            $vol = Get-BitLockerVolume -MountPoint $env:SystemDrive -ErrorAction Stop
            $protected = ($vol.ProtectionStatus -eq 'On')
        } catch { $protected = $false }
        if (-not $protected) {
            Write-Warning 'BitLocker is NOT on for the system disk. Client records will be stored on this laptop: turn on BitLocker (Settings > Privacy & security > Device encryption).'
            $sheet += @('UYARI: Bu dizustunun diski BitLocker ile sifreli DEGIL.',
                'Danisan kayitlari bu bilgisayarda durur: Ayarlar > Gizlilik ve guvenlik > Cihaz sifreleme / BitLocker acin.', '')
        } else {
            Write-Host '   BitLocker is on.'
        }
    }

    if ($fresh) {
        Step 'Generating passwords'
        $owner = New-Secret; $appPw = New-Secret; $syncPw = New-Secret; $backupPw = New-Secret
        $values = [ordered]@{
            'LOCAL_MIGRATION_DATABASE_URL' = "postgresql+asyncpg://kasa_migrator:$owner@127.0.0.1:$Port/kasa"
            'LOCAL_DATABASE_URL'           = "postgresql+asyncpg://kasa_app:$appPw@127.0.0.1:$Port/kasa"
            'LOCAL_SYNC_DATABASE_URL'      = "postgresql+asyncpg://kasa_sync:$syncPw@127.0.0.1:$Port/kasa"
            'LOCAL_APP_DB_PASSWORD'        = $appPw
            'LOCAL_SYNC_DB_PASSWORD'       = $syncPw
            'LOCAL_BACKUP_DB_PASSWORD'     = $backupPw
            'LOCAL_BACKUP_DATABASE_URL'    = "postgresql://kasa_backup:$backupPw@127.0.0.1:$Port/kasa"
            'LOCAL_COOKIE_SECURE'          = 'true'
        }
        if ($mode -eq 'office') {
            $generated = & $Py -c @"
from cryptography.fernet import Fernet
from pyrage import x25519
i = x25519.Identity.generate()
print(Fernet.generate_key().decode()); print(Fernet.generate_key().decode())
print(str(i)); print(str(i.to_public()))
"@
            if ($LASTEXITCODE -ne 0) { throw 'key generation failed' }
            $fernet, $authKey, $agePrivate, $agePublic = $generated
            $values['LOCAL_MODE'] = 'office'
            $values['LOCAL_FERNET_KEYS'] = $fernet
            $values['LOCAL_AUTH_FERNET_KEY'] = $authKey
            $values['BACKUP_AGE_RECIPIENT'] = $agePublic
            $values['BACKUP_RCLONE_REMOTE'] = ''
        } else {
            Step 'Reading the pairing file'
            Write-EnvFile $values  # the launcher needs a file to start
            $env:KLINIK_PAIRING_PASSPHRASE = $p['pairing_pass']
            try {
                $out = & $Py -m klinik_local.service --env $EnvFile manage import-pairing $p['pairing_file'] --cert-out (Join-Path $Config 'office.crt') 2>&1
                if ($LASTEXITCODE -ne 0) { throw "The pairing file could not be read: $out" }
            } finally { Remove-Item Env:KLINIK_PAIRING_PASSPHRASE -ErrorAction SilentlyContinue }
            foreach ($line in $out) {
                $i = "$line".IndexOf('=')
                if ($i -gt 0) { $values["$line".Substring(0, $i)] = "$line".Substring($i + 1) }
            }
            if ($values['LOCAL_MODE'] -ne 'replica') { throw 'The pairing file did not contain the expected values.' }
            Write-Host "   office: $($values['LOCAL_OFFICE_URL'])"
        }

        Step 'Creating the database (PostgreSQL 16)'
        $pwFile = Join-Path $env:TEMP "klinik-pw-$stamp.txt"
        [IO.File]::WriteAllText($pwFile, $owner)
        try {
            Invoke-Checked (Join-Path $PgBin 'initdb.exe') @('-D', $PgData, '-U', 'kasa_migrator', "--pwfile=$pwFile",
                '--encoding=UTF8', '--locale=C', '--auth=scram-sha-256', '--no-instructions')
        } finally { Remove-Item -LiteralPath $pwFile -Force -ErrorAction SilentlyContinue }
        Add-Content -LiteralPath (Join-Path $PgData 'postgresql.conf') -Encoding ASCII -Value @(
            '', '# Nil Psikoloji: only this computer may connect to the database.',
            "listen_addresses = '127.0.0.1'", "port = $Port")
        & icacls $PgData /grant 'NT AUTHORITY\NetworkService:(OI)(CI)F' | Out-Null
        & icacls $Data /grant 'NT AUTHORITY\NetworkService:(RX)' | Out-Null
        Invoke-Checked (Join-Path $PgBin 'pg_ctl.exe') @('register', '-N', 'KlinikPostgres', '-U', 'NT AUTHORITY\NetworkService',
            '-D', $PgData, '-S', 'auto', '-w')

        $sheet += @(
            'NIL PSIKOLOJI - KLINIK - ANAHTAR SAYFASI',
            "Bilgisayar: $Host_ ($(if ($mode -eq 'laptop') { 'klinik sahibinin dizustu kopyasi' } else { 'ofis bilgisayari' }))",
            "Olusturulma: $(Get-Date -Format 'dd.MM.yyyy HH:mm')",
            '',
            'BU SAYFAYI YAZDIRIN, GUVENLI BIR YERDE SAKLAYIN,',
            'SONRA BU DOSYAYI BILGISAYARDAN SILIN (Geri Donusum Kutusunu da bosaltin).',
            ''
        )
        if ($mode -eq 'office') {
            $sheet += @(
                '1) Seans notlarini ve danisan bilgilerini acan anahtar (LOCAL_FERNET_KEYS).',
                '   Kaybolursa notlar YEDEKTEN BILE geri getirilemez:',
                "   $fernet",
                '',
                '2) Yedek dosyalarini acan ozel anahtar. Bu bilgisayarda SAKLANMAZ:',
                "   $agePrivate",
                '',
                '3) Iki adimli dogrulama kayitlarinin anahtari (LOCAL_AUTH_FERNET_KEY):',
                "   $authKey",
                ''
            )
        }
        $sheet += @('Veritabani yonetici sifresi (kasa_migrator) - yalnizca bu bilgisayar icin:', "   $owner")
    } else {
        Step 'Existing installation found: keeping data and keys'
        $values = $existing
        foreach ($obsolete in @('LOCAL_WEB_BASE_URL', 'SYNC_LOCAL_DATABASE_URL', 'SYNC_CLOUD_BASE_URL', 'SYNC_CLOUD_TOKEN',
                'KLINIK_KASA_PORT', 'KLINIK_SYNC_PORT', 'BACKUP_CLOUD_DUMP_URL')) {
            if ($values.Contains($obsolete)) { $values.Remove($obsolete) }
        }
        if (-not $values.Contains('LOCAL_SYNC_DATABASE_URL')) {
            $values['LOCAL_SYNC_DATABASE_URL'] = "postgresql+asyncpg://kasa_sync:$($values['LOCAL_SYNC_DB_PASSWORD'])@127.0.0.1:$Port/kasa"
        }
        if (-not $values.Contains('LOCAL_MODE')) { $values['LOCAL_MODE'] = 'office' }
        $values['LOCAL_COOKIE_SECURE'] = 'true'
    }

    # ------------------------------------------------------------ HTTPS
    $cert = Join-Path $Tls 'klinik.crt'
    if (-not (Test-Path $cert)) {
        Step 'Creating this computer''s HTTPS certificate'
        Write-EnvFile $values
        $names = @('--name', 'localhost', '--name', '127.0.0.1')
        if ($mode -eq 'office') { $names += @('--name', $Host_, '--name', "$($Host_.ToLower()).local") }
        Invoke-Manage (@('generate-cert', '--out', $Tls) + $names) | ForEach-Object { Write-Host "   $_" }
        # Browsers on this computer trust it (no warning at https://localhost:8443).
        Import-Certificate -FilePath $cert -CertStoreLocation Cert:\LocalMachine\Root | Out-Null
    }
    & icacls $Tls /inheritance:r /grant:r 'SYSTEM:(OI)(CI)F' '*S-1-5-32-544:(OI)(CI)F' | Out-Null

    # Paths may change between versions; always refresh them.
    $values['KLINIK_TLS_CERT'] = $cert
    $values['KLINIK_TLS_KEY'] = Join-Path $Tls 'klinik.key'
    $values['KLINIK_PORT'] = "$HttpsPort"
    $values['KLINIK_ALEMBIC_INI'] = Join-Path $App 'app\alembic.ini'
    $values['KLINIK_MIGRATIONS_DIR'] = Join-Path $App 'app\migrations\local'
    if ($mode -eq 'office') {
        # The owner's laptop reaches the office over the office network.
        $values['KLINIK_BIND'] = '0.0.0.0'
        $values['LOCAL_PUBLIC_URL'] = "https://$($Host_):$HttpsPort"
        $values['LOCAL_TLS_CERT'] = $cert
        $values['LOCAL_PG_BIN'] = $PgBin
        $values['LOCAL_BACKUP_DIR'] = Join-Path $Data 'backups'
        $values['LOCAL_SNAPSHOT_DIR'] = Join-Path $Data 'ozet'
        $values['RCLONE_EXE'] = Join-Path $App 'tools\rclone.exe'
        $values['RCLONE_CONFIG'] = Join-Path $Config 'rclone.conf'
    } else {
        $values['KLINIK_BIND'] = '127.0.0.1'
    }
    Write-EnvFile $values

    if ($mode -eq 'office') {
        Step 'Firewall: allowing the office network (private networks only)'
        Get-NetFirewallRule -DisplayName 'Nil Psikoloji Klinik (HTTPS)' -ErrorAction SilentlyContinue | Remove-NetFirewallRule
        New-NetFirewallRule -DisplayName 'Nil Psikoloji Klinik (HTTPS)' -Direction Inbound -Protocol TCP `
            -LocalPort $HttpsPort -Profile Private -RemoteAddress LocalSubnet -Action Allow | Out-Null
        $public = Get-NetConnectionProfile -ErrorAction SilentlyContinue | Where-Object { $_.NetworkCategory -eq 'Public' }
        if ($public) {
            Write-Warning "The network '$($public[0].Name)' is set to PUBLIC: the owner's laptop cannot sync until it is set to PRIVATE (Settings > Network > Properties > Private)."
        }
    }

    Step 'Starting the database'
    Start-Service -Name KlinikPostgres
    for ($i = 0; $i -lt 60; $i++) {
        & (Join-Path $PgBin 'pg_isready.exe') -h 127.0.0.1 -p $Port -q
        if ($LASTEXITCODE -eq 0) { break }
        Start-Sleep -Seconds 1
    }
    if ($fresh) {
        $env:PGPASSWORD = $owner
        Invoke-Checked (Join-Path $PgBin 'psql.exe') @('-h', '127.0.0.1', '-p', "$Port", '-U', 'kasa_migrator', '-d', 'postgres',
            '-q', '-c', 'CREATE DATABASE kasa')
        Remove-Item Env:PGPASSWORD
    }

    Step 'Updating the database structure'
    Invoke-Checked $Py @('-m', 'klinik_local.service', '--env', $EnvFile, 'migrate')

    if ($fresh -and $mode -eq 'office' -and $p['admin_user']) {
        Step 'Creating the admin user'
        $out = Invoke-Manage @('create-user', '--username', $p['admin_user'], '--name', $p['admin_name'], '--role', 'admin')
        $sheet += @('', 'Ilk giris (gecici sifre; ilk giriste degistirilir, sonra iki adimli dogrulama kurulur):')
        foreach ($line in $out) {
            if ("$line" -match '^created (\S+)\s+temporary password: (\S+)') { $sheet += "   Kullanici: $($Matches[1])   Gecici sifre: $($Matches[2])" }
        }
        $sheet += '   Terapistleri programda Ayarlar > Kullanicilar sayfasindan ekleyin.'
    }

    if ($mode -eq 'laptop') {
        Step 'First copy from the office'
        $out = & $Py -m klinik_local.service --env $EnvFile manage replica-sync 2>&1
        if ($LASTEXITCODE -eq 0) {
            Write-Host "   $out"
        } else {
            Write-Warning "The office could not be reached now ($out). The copy is made automatically as soon as this laptop is on the office network; sign-in works after that."
            $sheet += @('', 'NOT: Ilk esitleme yapilamadi. Dizustu ofis agina baglaninca otomatik yapilir;', '     kullanicilar ve kayitlar ancak ondan sonra gelir.')
        }
    }

    Step 'Installing Windows services'
    $serviceDir = Join-Path $App 'services'
    New-Item -ItemType Directory -Force -Path $serviceDir | Out-Null
    $defs = @(@{ id = 'KlinikApp'; target = 'app'; name = 'Nil Psikoloji - Klinik'; desc = "Klinik programi ($LocalUrl)" })
    if ($mode -eq 'office') {
        $defs += @{ id = 'KlinikJobs'; target = 'jobs'; name = 'Nil Psikoloji - Yedekleme ve ozet'; desc = 'Gece yedegi, saatlik yedek, 17:00 gunluk ozet' }
    }
    foreach ($s in $defs) {
        $exe = Join-Path $serviceDir "$($s.id).exe"
        if (Get-Service -Name $s.id -ErrorAction SilentlyContinue) {
            & $exe uninstall | Out-Null
            Start-Sleep -Seconds 2
        }
        Copy-Item -LiteralPath (Join-Path $App 'tools\winsw.exe') -Destination $exe -Force
        $xml = @"
<service>
  <id>$($s.id)</id>
  <name>$($s.name)</name>
  <description>$($s.desc)</description>
  <executable>$Py</executable>
  <arguments>-m klinik_local.service --env "$EnvFile" $($s.target)</arguments>
  <workingdirectory>$(Join-Path $App 'app')</workingdirectory>
  <startmode>Automatic</startmode>
  <depend>KlinikPostgres</depend>
  <onfailure action="restart" delay="10 sec"/>
  <onfailure action="restart" delay="30 sec"/>
  <resetfailure>1 hour</resetfailure>
  <logpath>$Logs</logpath>
  <log mode="roll-by-size"><sizeThreshold>10240</sizeThreshold><keepFiles>5</keepFiles></log>
</service>
"@
        [IO.File]::WriteAllText((Join-Path $serviceDir "$($s.id).xml"), $xml, (New-Object Text.UTF8Encoding($false)))
        Invoke-Checked $exe @('install')
    }

    if ($mode -eq 'office' -and $p['drive'] -eq '1' -and -not $values['BACKUP_RCLONE_REMOTE']) {
        Step 'Connecting Google Drive (a browser window opens: sign in with the clinic account)'
        & (Join-Path $App 'tools\rclone.exe') config create klinik-drive drive scope=drive.file --config (Join-Path $Config 'rclone.conf')
        if ($LASTEXITCODE -eq 0) {
            $values['BACKUP_RCLONE_REMOTE'] = 'klinik-drive:Nil Psikoloji'
            Write-EnvFile $values
            Write-Host '   Google Drive connected: folder "Nil Psikoloji" (yedek, ozet)'
        } else {
            Write-Warning 'Google Drive could not be connected. Backups stay on this computer; run setup again later.'
        }
    }

    Step 'Starting services'
    foreach ($s in $defs) { Start-Service -Name $s.id }
    $ok = $false
    for ($i = 0; $i -lt 90; $i++) {
        try {
            $r = Invoke-WebRequest -UseBasicParsing -Uri "$LocalUrl/healthz" -TimeoutSec 3
            if ($r.StatusCode -eq 200) { $ok = $true; break }
        } catch { Start-Sleep -Seconds 1 }
    }
    if (-not $ok) { throw "The program did not answer at $LocalUrl (see $Logs)" }

    if ($sheet.Count -gt 0) {
        $sheet += @('', "Program adresi (bu bilgisayarda): $LocalUrl")
        if ($mode -eq 'office') {
            $sheet += @("Dizustu kopyanin ofise ulastigi adres: https://$($Host_):$HttpsPort",
                'Dizustu kopya: programda Ayarlar > Dizustu kopya sayfasindan eslestirme dosyasi olusturun.')
        }
        $sheet += @("Ayarlar dosyasi: $EnvFile")
        $desktop = [Environment]::GetFolderPath('Desktop')
        $sheetFile = Join-Path $desktop 'NIL-KLINIK-ANAHTARLAR.txt'
        [IO.File]::WriteAllLines($sheetFile, $sheet, (New-Object Text.UTF8Encoding($true)))
        Write-Host ''
        Write-Host "KEY SHEET: $sheetFile  -> print it, store it offline, then delete it." -ForegroundColor Yellow
        Start-Process notepad.exe $sheetFile
    }
    Step "Ready: $LocalUrl"
    exit 0
} catch {
    Write-Host ''
    Write-Host "SETUP FAILED: $($_.Exception.Message)" -ForegroundColor Red
    Write-Host "Log: $Logs"
    Read-Host 'Press Enter to close' | Out-Null
    exit 1
} finally {
    Stop-Transcript | Out-Null
}
